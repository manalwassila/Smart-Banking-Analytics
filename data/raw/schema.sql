-- Smart Banking Morocco — PostgreSQL schema (synthetic educational dataset v2.0)
-- Import CSV files first, then add constraints as below.
CREATE TABLE clients (
  SK_ID_CURR BIGINT PRIMARY KEY,
  AGE INT, GENDER VARCHAR(5), MARITAL_STATUS VARCHAR(30), EDUCATION_LEVEL VARCHAR(30),
  CITY VARCHAR(50), EMPLOYMENT_STATUS VARCHAR(40), EMPLOYMENT_CONTRACT VARCHAR(40),
  EMPLOYMENT_YEARS NUMERIC(5,1), HOUSING_STATUS VARCHAR(30), HOUSEHOLD_SIZE INT,
  DEPENDENTS INT, BANK_TENURE_YEARS NUMERIC(5,1), ACCOUNT_TYPE VARCHAR(40),
  NUMBER_OF_CHILDREN INT, DEPENDENT_CHILDREN INT, OTHER_DEPENDENTS INT,
  HAS_FINANCIAL_DEPENDENTS SMALLINT, FAMILY_RESPONSIBILITY_LEVEL VARCHAR(20)
);
CREATE TABLE financial_profiles (
  SK_ID_CURR BIGINT PRIMARY KEY REFERENCES clients(SK_ID_CURR),
  MONTHLY_INCOME_MAD NUMERIC, MONTHLY_EXPENSES_MAD NUMERIC, EXISTING_DEBT_MAD NUMERIC,
  OTHER_MONTHLY_PAYMENTS_MAD NUMERIC, SAVINGS_MAD NUMERIC, AVG_ACCOUNT_BALANCE_MAD NUMERIC,
  INCOME_SOURCE VARCHAR(50), MONTHLY_FAMILY_EXPENSES_MAD NUMERIC,
  ADDITIONAL_MONTHLY_INCOME_MAD NUMERIC, HOUSEHOLD_MONTHLY_INCOME_MAD NUMERIC,
  TOTAL_MONTHLY_COMMITMENTS_MAD NUMERIC, DISPOSABLE_INCOME_MAD NUMERIC,
  HOUSEHOLD_EXPENSE_RATIO NUMERIC, SAVINGS_TO_MONTHLY_INCOME NUMERIC
);
CREATE TABLE credit_applications (
  SK_ID_CURR BIGINT PRIMARY KEY REFERENCES clients(SK_ID_CURR),
  APPLICATION_DATE DATE, CREDIT_TYPE VARCHAR(40), AMOUNT_REQUESTED_MAD NUMERIC,
  CREDIT_TERM_MONTHS INT, INTEREST_RATE_ANNUAL_PCT NUMERIC,
  ESTIMATED_MONTHLY_INSTALLMENT_MAD NUMERIC, CREDIT_TO_ANNUAL_INCOME NUMERIC,
  PAYMENT_TO_INCOME_RATIO NUMERIC, DEBT_TO_INCOME_RATIO NUMERIC,
  TARGET SMALLINT, TARGET_LABEL VARCHAR(80)
);
CREATE TABLE assets (
  SK_ID_CURR BIGINT PRIMARY KEY REFERENCES clients(SK_ID_CURR),
  OWNS_PROPERTY SMALLINT, NUMBER_OF_PROPERTIES INT, PROPERTY_TYPE VARCHAR(40),
  TOTAL_PROPERTY_VALUE_MAD NUMERIC, PROPERTY_FULLY_PAID SMALLINT,
  OUTSTANDING_MORTGAGE_MAD NUMERIC, MONTHLY_RENTAL_INCOME_MAD NUMERIC,
  OTHER_FINANCIAL_ASSETS_MAD NUMERIC, NET_PROPERTY_VALUE_MAD NUMERIC
);
CREATE TABLE insurance (
  SK_ID_CURR BIGINT PRIMARY KEY REFERENCES clients(SK_ID_CURR),
  HAS_LIFE_INSURANCE SMALLINT, HAS_LOAN_PROTECTION_INSURANCE SMALLINT,
  LIFE_COVERAGE_AMOUNT_MAD NUMERIC, LOAN_PROTECTION_COVERAGE_AMOUNT_MAD NUMERIC,
  TOTAL_MONTHLY_INSURANCE_PREMIUM_MAD NUMERIC, INSURANCE_CONTRACT_STATUS VARCHAR(50)
);
CREATE TABLE decision_scenarios (
  SK_ID_CURR BIGINT PRIMARY KEY REFERENCES clients(SK_ID_CURR),
  DEMO_RISK_SCORE NUMERIC, DEMO_RISK_LEVEL VARCHAR(20),
  MAX_AFFORDABLE_MONTHLY_INSTALLMENT_MAD NUMERIC,
  MAX_AFFORDABLE_LOAN_AMOUNT_MAD NUMERIC, RECOMMENDED_DECISION VARCHAR(40),
  RECOMMENDED_FINANCING_RATIO NUMERIC, RECOMMENDED_LOAN_AMOUNT_MAD NUMERIC,
  PROPOSED_ANNUAL_INTEREST_RATE_PCT NUMERIC,
  ESTIMATED_NEW_MONTHLY_INSTALLMENT_MAD NUMERIC,
  HUMAN_VALIDATION_STATUS VARCHAR(50), POLICY_SCENARIO_VERSION VARCHAR(40)
);
